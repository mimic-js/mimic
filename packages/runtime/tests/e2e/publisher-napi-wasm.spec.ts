function lightningCssWorkloadSource(
  packageName = 'lightningcss-wasm',
  installPath = 'node_modules/lightningcss-wasm'
): string {
  return String.raw`
const result = document.querySelector('#result');
try {
  const module = await import(${JSON.stringify(packageName)});
  await module.default();
  const inputs = ['.answer { color: rgb(255, 0, 0); }', '.layout { display: flex; user-select: none; }'];
  const transforms = inputs.map((css, index) => {
    const transformed = module.transform({ filename: 'fixture-' + index + '.css', code: new TextEncoder().encode(css), minify: true });
    return new TextDecoder().decode(transformed.code);
  });
  let expectedError = 'NO ERROR';
  try { module.transform({ filename: 'broken.css', code: new TextEncoder().encode('@media ( { a{}') }); }
  catch (error) { expectedError = error instanceof Error ? error.name + ': ' + error.message : String(error); }
  const wasmUrl = new URL('/${installPath}/lightningcss_node.wasm', location.href);
  const wasmModule = await WebAssembly.compileStreaming(fetch(wasmUrl));
  const wasmImports = WebAssembly.Module.imports(wasmModule).map((entry) => entry.module + '.' + entry.name);
  globalThis.__lightningCssProbe = { outcome: 'success', transforms, expectedError, wasmImports };
} catch (error) {
  globalThis.__lightningCssProbe = { outcome: 'failure', error: error instanceof Error ? error.stack || error.message : String(error) };
}
result.textContent = JSON.stringify(globalThis.__lightningCssProbe);
`;
}
