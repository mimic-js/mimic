type LightningCssProbe = PublisherProbe &
  Readonly<{
    transforms?: readonly string[];
    expectedError?: string;
    wasmImports?: readonly string[];
    error?: string;
  }>;

test(lightningCssCompatibilityClaim.statement, async ({ page }) => {
  test.setTimeout(600_000);
  const result = await runTrackedPublisherArtifactFixture<LightningCssProbe>(
    page,
    lightningCssPublisherFixture,
    lightningCssInstallFixture,
    lightningCssWorkloadSource(),
    '__lightningCssProbe',
    'Lightning CSS publisher probe',
    process.env.GITHUB_SHA ?? 'local',
    Object.keys(lightningCssCompatibilityClaim.target.replacements)
  );

  expect(result.install.exitCode, result.install.output).toBe(0);
  expect(result.executionCapacity).toMatchObject({
    runtimePlatform: {
      hardwareConcurrency: 2,
      executionCapacity: 1
    },
    observedCapacity: 1,
    capacityFailure: {
      code: 'CAPACITY_EXHAUSTED',
      message: 'Execution Capacity 1 is exhausted.'
    },
    independent: {
      exitCode: 0,
      output: expect.stringContaining('capacity-one-yarn-workload')
    }
  });
  const forbiddenCapacityFailure = /(?:\bEAGAIN\b|Execution Capacity \d+ is exhausted)/;
  for (const output of [
    result.install.output,
    result.executionCapacity!.independent.output,
    result.devOutput
  ]) {
    expect(output).not.toMatch(forbiddenCapacityFailure);
  }
  expect(result.lockfile).toEqual({ mountedBeforeInstall: true, unchangedAfterInstall: true });
  expect(result.identity.evidence).toEqual({ runner: 'playwright', publicMimicApi: true });
  expect(result.security.contentSecurityPolicy).toBe(PUBLISHER_ARTIFACT_CONTENT_SECURITY_POLICY);
  expect(result.identity.replacements).toEqual(lightningCssCompatibilityClaim.target.replacements);
  expect(result.probe).toMatchObject({
    outcome: 'success',
    transforms: ['.answer{color:red}', '.layout{user-select:none;display:flex}'],
    expectedError: expect.stringMatching(/^SyntaxError:/),
    wasmImports: expect.arrayContaining(['env.napi_create_buffer', 'env.napi_create_buffer_copy'])
  });

  expect(result.artifacts).toEqual([
    {
      path: lightningCssPublisherFixture.artifacts[0].path,
      role: 'wasm',
      expectedSha256: lightningCssPublisherFixture.artifacts[0].sha256,
      actualSha256: lightningCssPublisherFixture.artifacts[0].sha256,
      servedSha256: lightningCssPublisherFixture.artifacts[0].sha256,
      servedFromVfs: true
    }
  ]);
  expect(result.fallbackScan.observed).toEqual([]);
  expect(result.teardown).toEqual({ completed: true });
  expect(result.reboot).toEqual({ completed: true });
  expect(result.diagnostics.artifactResponses).toEqual(
    expect.arrayContaining([expect.stringMatching(/^200 application\/wasm .*lightningcss_node\.wasm$/)])
  );
  expect(result.diagnostics.pageErrors).toEqual([]);
  expect(result.diagnostics.failedRequests).toEqual([]);
});

