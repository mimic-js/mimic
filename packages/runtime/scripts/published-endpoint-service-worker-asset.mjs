import { readFile } from 'node:fs/promises';
// service.ts, not the published-endpoint barrel: the barrel also re-exports the
// page-side client and browser host, which a Node build step has no use for.
import { PUBLISHED_ENDPOINT_SERVICE_WORKER_TOKEN } from '../src/runtime/modules/published-endpoint/service.ts';
import { workerTransportBrowserArtifactSource } from '../src/runtime/modules/worker-transport/index.ts';

export const publishedEndpointServiceWorkerProgram = new URL(
  '../src/runtime/modules/published-endpoint/service-worker-program.js',
  import.meta.url
);
export const publishedEndpointServiceWorkerAsset = new URL(
  '../src/runtime/modules/published-endpoint/service-worker.js',
  import.meta.url
);

/**
 * The committed `service-worker.js`: the embedded Worker Transport, the
 * protocol token from its TypeScript owner, then the Published Endpoint program.
 * The transport is `Function.prototype.toString` output, so the text depends on
 * the transpiler that loaded it; run this under `tsx`, as the build does.
 */
export async function publishedEndpointServiceWorkerAssetSource() {
  const programSource = await readFile(publishedEndpointServiceWorkerProgram, 'utf8');
  return [
    '// Generated by scripts/build-runtime-assets.mjs from Worker Transport and Published Endpoint-owned sources.\n',
    workerTransportBrowserArtifactSource(),
    '\n\n',
    `const PUBLISHED_ENDPOINT_SERVICE_WORKER_TOKEN = ${JSON.stringify(PUBLISHED_ENDPOINT_SERVICE_WORKER_TOKEN)};\n`,
    // The scope document serves `fetch` to a cross-origin embedding page over
    // the same transport (ADR-0032), so the worker carries its source as text.
    `const WORKER_TRANSPORT_SOURCE = ${JSON.stringify(workerTransportBrowserArtifactSource())};\n`,
    programSource
  ].join('');
}
